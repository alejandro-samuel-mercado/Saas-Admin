import { PaymentStatus, PaymentType, UserRole, Rubro } from "./schema";

export interface Product {
  id: number;
  name: string;
  basePrice: number;
  stock: number;
  category: Category;
  isActive: boolean;
  description?: string;
  images?: string[];
  skus?: SKU[];

  measurementUnit: string;
  allowFractional: boolean;

  createdAt?: string;
  brand?: string;
  model?: string;
  pointsValue?: number;
  taxRate?: number;
}

export interface SKU {
  id: number;
  isAutoGenerated: boolean;
  price: number;
  costPrice?: number;
  productId: number;
  attributes?: VariantOption[];
}

export interface VariantOption {
  name: string;
  value: string;
}

export interface Category {
  id: number;
  name: string;
  slug: string;
}

export interface User {
  id: number;
  name: string;
  email: string;
  role: UserRole;
  points: number;
}

export interface Sale {
  id: number;
  uuid: string;
  total: number;
  items: any[];
  createdAt: string;
  paymentStatus: PaymentStatus;
  paymentType: PaymentType;
  pointsUsed?: number;
  pointsDiscount?: number;
}

